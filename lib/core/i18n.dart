const supportedLanguages = ['en', 'pt'];

bool get isPt => Prefs.instance.language == 'pt';

Locale get appLocale => isPt ? const Locale('pt', 'BR') : const Locale('en');

String tr(String en, [Map<String, Object?> args = const {}]) {
  var s = isPt ? (_pt[en] ?? en) : en;
  args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  return s;
}

String callText(String body) {
  final i = body.indexOf(' · ');
  if (i < 0) return tr(body);
  return '${tr(body.substring(0, i))}${body.substring(i)}';
}

void rebuildAll(BuildContext context) {
  void mark(Element e) {
    e.markNeedsBuild();
    e.visitChildren(mark);
  }

  (context as Element).visitChildren(mark);
}

